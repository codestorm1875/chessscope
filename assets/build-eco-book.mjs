// Builds eco-book.js (all Lichess ECO opening positions) from the TSV files.
// Usage: place a.tsv..e.tsv from https://github.com/lichess-org/chess-openings
// next to this script (or pass the directory), then:
//   node assets/build-eco-book.mjs [tsv-dir]
// Output: eco-book.js at the repo root (generated, committed).
// Each entry: [positionKey, eco, baseName, variation, ply]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parsePgn } from '../chess.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tsvDir = process.argv[2] || path.dirname(fileURLToPath(import.meta.url));
const positionKey = fen => fen?.split(' ').slice(0, 3).join(' ');

const seen = new Map(); // key -> entry (first, i.e. shortest/canonical line wins)
let parsed = 0;
const failures = [];
for (const file of ['a', 'b', 'c', 'd', 'e']) {
  const text = await readFile(path.join(tsvDir, `eco-${file}.tsv`), 'utf8');
  const lines = text.split('\n').slice(1).filter(l => l.trim());
  for (const line of lines) {
    const [eco, name, pgn] = line.split('\t');
    if (!eco || !name || !pgn) { failures.push(`malformed: ${line.slice(0, 60)}`); continue; }
    let game;
    try { game = parsePgn(pgn); }
    catch (error) { failures.push(`${eco} ${name}: ${error.message}`); continue; }
    parsed++;
    const key = positionKey(game.finalFen);
    if (seen.has(key)) continue;
    const colon = name.indexOf(':');
    const base = (colon < 0 ? name : name.slice(0, colon)).trim();
    const variation = colon < 0 ? 'Main line' : name.slice(colon + 1).trim();
    seen.set(key, [key, eco.trim(), base, variation, game.moves.length]);
  }
}

const entries = [...seen.values()].sort((a, b) => a[4] - b[4] || (a[1] < b[1] ? -1 : 1));
const out = `// GENERATED by assets/build-eco-book.mjs — do not edit by hand.\n// Source: lichess-org/chess-openings (ECO codes, names, PGN lines).\n// Entry: [positionKey, eco, baseName, variation, ply].\nexport const ECO_POSITIONS=${JSON.stringify(entries)};\n`;
await writeFile(path.join(root, 'eco-book.js'), out);
console.log(`ECO book: ${entries.length} positions from ${parsed} lines`);
if (failures.length) {
  console.log(`${failures.length} skipped:`);
  failures.slice(0, 10).forEach(f => console.log('  ' + f));
}
